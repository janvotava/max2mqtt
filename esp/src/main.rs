/// A password for the hotspot and web UI when none was configured: 12 characters without
/// look-alikes, printed on the serial console.
fn generate_password() -> String {
    const ALPHABET: &[u8] = b"abcdefghjkmnpqrstuvwxyz23456789";
    let rng = Rng::new();
    (0..12).map(|_| ALPHABET[rng.random() as usize % ALPHABET.len()] as char).collect()
}

#[esp_rtos::main]
async fn main(spawner: Spawner) -> ! {
    let p = esp_hal::init(esp_hal::Config::default().with_cpu_clock(CpuClock::max()));
    logger::init();
    // Reclaimed sizes as generated by esp-generate for each chip.
    #[cfg(feature = "c3-mini")]
    esp_alloc::heap_allocator!(#[esp_hal::ram(reclaimed)] size: 66320);
    #[cfg(feature = "d1-mini-esp32")]
    esp_alloc::heap_allocator!(#[esp_hal::ram(reclaimed)] size: 98768);
    // The ESP32 has more internal RAM to spare than the C3.
    #[cfg(feature = "c3-mini")]
    esp_alloc::heap_allocator!(size: 64 * 1024);
    #[cfg(feature = "d1-mini-esp32")]
    esp_alloc::heap_allocator!(size: 80 * 1024);
    logger::keep_lines();
    let pins = board::take_pins!(p);

    let timg0 = TimerGroup::new(p.TIMG0);
    esp_rtos::start(timg0.timer0, p.FROM_CPU_INTR0);
    log::info!("max2mqtt {} starting on {}", env!("CARGO_PKG_VERSION"), board::NAME);
    heap::step("start");

    // Burner off until the bridge decides otherwise.
    let relay = Output::new(pins.relay, Level::Low, OutputConfig::default());
    // Restart if the firmware stops running for 30 s; the control loop feeds it.
    let mut watchdog = esp_hal::rtc_cntl::Rtc::new(p.RTC_TIMER).rwdt;
    watchdog.set_timeout(esp_hal::rtc_cntl::RwdtStage::Stage0, esp_hal::time::Duration::from_secs(30));
    watchdog.enable();

    let mut store = Store::open(FlashStorage::new(p.FLASH));
    let loaded = match &mut store {
        Some(s) => s.load().await,
        None => Loaded { settings: None, config: None },
    };
    if let Some(c) = crash::take() {
        log::error!("Restarted after a crash: {} (backtrace {})", c.reason, c.backtrace.join(" "));
        if let Some(s) = &mut store {
            s.add_crash(c).await;
        }
    }
    let on_trial = match &mut store {
        Some(s) => ota::check_boot(s).await,
        None => false,
    };
    let mut settings = match loaded.settings {
        Some(s) => {
            log::info!("Loaded settings");
            s
        }
        None => {
            log::info!("No stored settings, using the build defaults");
            settings::defaults()
        }
    };
    if settings.password.len() < 8 {
        settings.password = generate_password();
        log::warn!("Generated the device password: {}", settings.password);
        if let Some(s) = &mut store
            && let Err(e) = s.save_settings(&settings).await
        {
            log::error!("Saving settings failed: {e:?}");
        }
    }
    // Every boot, so a forgotten password can be read here (physical access only).
    log::info!("Device password (web UI, setup hotspot): {}", settings.password);
    if let Err(e) = settings.validate() {
        log::error!("Settings are invalid: {e}");
    }
    static SETTINGS: StaticCell<Settings> = StaticCell::new();
    let settings: &'static Settings = SETTINGS.init(settings);
    static STORE: StaticCell<SharedStore> = StaticCell::new();
    let store: &'static SharedStore = STORE.init(Mutex::new(store));

    let config = match loaded.config {
        Some(c) => {
            log::info!("Loaded config with {} devices", c.devices.len());
            c
        }
        None => {
            log::info!("No stored config, starting with defaults");
            Config::default()
        }
    };
    let topics = Topics {
        prefix: settings.mqtt.prefix.clone(),
        discovery: settings.mqtt.homeassistant.then(|| settings.mqtt.discovery_prefix.clone()),
    };
    *BRIDGE.lock().await = Some(Bridge::new(config, topics, Instant::now().as_millis()));
    heap::step("loading settings and devices");

    let spi = Spi::new(p.SPI2, SpiConfig::default().with_frequency(Rate::from_mhz(4)))
        .expect("SPI config")
        .with_sck(pins.sck)
        .with_miso(pins.miso)
        .with_mosi(pins.mosi)
        .into_async();
    let cs = Output::new(pins.cs, Level::High, OutputConfig::default());
    let gdo2 = Input::new(pins.gdo2, InputConfig::default());
    let radio = cc1101::Cc1101::new(spi, cs, settings.cc1101_freq_offset);

    let net = net::start(&spawner, p.WIFI, settings);
    heap::step("starting Wi-Fi");
    let mac = net.mac;
    static CLIENT_ID: StaticCell<String> = StaticCell::new();
    let client_id = CLIENT_ID.init(format!("max-{:02x}{:02x}{:02x}", mac[3], mac[4], mac[5]));

    static APP: StaticCell<web::App> = StaticCell::new();
    let app = APP.init(web::App { settings, store, hotspot_ssid: net.hotspot_ssid, station: net.station });

    spawner.spawn(radio::radio_task(radio, gdo2).unwrap());
    if settings.mqtt.host.is_empty() {
        log::warn!("MQTT is off: no broker configured");
    } else {
        spawner.spawn(mqtt::mqtt_task(net.station, client_id, settings).unwrap());
    }
    spawner.spawn(control_task(relay, watchdog).unwrap());
    spawner.spawn(system_task(store).unwrap());
    if on_trial {
        spawner.spawn(ota::confirm_task(store, !settings.wifi.ssid.is_empty()).unwrap());
    }
    spawner.spawn(portal::portal_task(net.hotspot).unwrap());
    // A page loads several things at once; a connection that finds no listener is refused.
    for _ in 0..4 {
        spawner.spawn(web::web_task(net.station, false, app).unwrap());
    }
    for _ in 0..2 {
        spawner.spawn(web::web_task(net.hotspot, true, app).unwrap());
    }
    // The tasks allocate their buffers when they first run.
    Timer::after_secs(5).await;
    heap::step("starting the tasks (web, MQTT, radio)");

    loop {
        Timer::after_secs(3600).await;
    }
}

/// Once a second: periodic bridge work and the burner relay.
#[embassy_executor::task]
async fn control_task(mut relay: Output<'static>, mut watchdog: esp_hal::rtc_cntl::Rwdt) {
    let mut ticker = Ticker::every(Duration::from_secs(1));
    loop {
        ticker.next().await;
        watchdog.feed();
        let save_failed = shared::SAVE_FAILED.try_take().is_some();
        let (effects, on, tz) = with_bridge(|b| {
            if save_failed {
                b.save_failed(ctx().now);
            }
            (b.tick(ctx()), b.burner_on(), b.timezone())
        })
        .await;
        shared::set_log_timezone(tz);
        relay.set_level(if on { Level::High } else { Level::Low });
        dispatch(effects);
    }
}

/// Flash writes and restarts, in the order they were requested.
#[embassy_executor::task]
async fn system_task(store: &'static SharedStore) {
    loop {
        let cmd = SYSTEM.receive().await;
        let mut guard = store.lock().await;
        let Some(store) = guard.as_mut() else {
            if cmd == SystemCmd::Restart {
                esp_hal::system::software_reset();
            }
            continue;
        };
        let result = match cmd {
            SystemCmd::SaveConfig => store.save_config(with_bridge(|b| b.config()).await).await,
            SystemCmd::FactoryReset => {
                log::warn!("Factory reset: erasing all settings and config, restarting");
                if let Err(e) = store.erase().await {
                    log::error!("Erasing failed: {e:?}");
                }
                Timer::after_millis(500).await;
                esp_hal::system::software_reset();
            }
            SystemCmd::Restart => {
                if let Err(e) = store.save_config(with_bridge(|b| b.config()).await).await {
                    log::error!("Saving config failed: {e:?}");
                }
                log::warn!("Restarting");
                // Let the MQTT and web tasks flush.
                Timer::after_millis(500).await;
                esp_hal::system::software_reset();
            }
        };
        if let Err(e) = result {
            log::error!("{cmd:?} failed: {e:?}");
            if cmd == SystemCmd::SaveConfig {
                shared::SAVE_FAILED.signal(());
            }
        }
    }
}
